/*
Category	        Operators
===========         ==============
Bitwise	            & | ^ ~ << >>
*/
console.log(5 & 1);     // 1    AND
console.log(5 | 1);     // 5    OR
console.log(5 ^ 1);     // 5    XOR
console.log(~5);        // -6   NOT
console.log(5 << 1);    // 10   left shift
console.log(5 >> 1);    // 2    right shift